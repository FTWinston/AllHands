import { shipAppearances } from 'common-data/features/space/types/ObjectAppearance';
import { svgStrings } from 'common-ui/objects/strings';
import { describe, expect, it } from 'vitest';
import { generateShieldOutline } from './generateShieldOutline';
import { getShieldDotPattern, getShieldPath, shieldDotCount, shieldDotSize, shieldOverhang } from './shieldOutline';

const viewBoxSize = 512;

const outlines = Object.fromEntries(shipAppearances.map(appearance => [appearance, generateShieldOutline(svgStrings[appearance])]));

function readPoints(path: string) {
    return [...path.matchAll(/(-?\d+) (-?\d+)/g)].map(match => ({ x: Number(match[1]), y: Number(match[2]) }));
}

describe('shield outlines', () => {
    // This test writes the generated file when run with --update. After changing a ship drawing or the outline settings, run:
    // npm run generate:shield-outlines
    it('are up to date with the ship drawings', async () => {
        const entries = shipAppearances.map(appearance => `    '${appearance}': '${outlines[appearance]}',`);

        const file = [
            '// Generated by shieldOutlines.test.ts from the ship drawings. Don\'t edit by hand: to update it, run',
            '// npm run generate:shield-outlines',
            'import type { ShipAppearance } from \'common-data/features/space/types/ObjectAppearance\';',
            '',
            '/** The outline that each ship design\'s shields are drawn along, starting at its nose. */',
            'export const shieldOutlines: Record<ShipAppearance, string> = {',
            ...entries,
            '};',
            '',
        ].join('\n');

        await expect(file).toMatchFileSnapshot('./shieldOutlines.generated.ts');
    });

    it.each(shipAppearances)('%s keeps its shield dots within the overhang around its drawing', (appearance) => {
        const reach = shieldDotSize / 2;

        for (const { x, y } of readPoints(outlines[appearance])) {
            expect(Math.min(x, y) - reach).toBeGreaterThanOrEqual(-shieldOverhang);
            expect(Math.max(x, y) + reach).toBeLessThanOrEqual(viewBoxSize + shieldOverhang);
        }
    });

    it.each(shipAppearances)('%s starts its outline at its nose, on the centreline', (appearance) => {
        const [start, ...rest] = readPoints(outlines[appearance]);

        expect(start.y).toBe(256);
        for (const point of rest.filter(point => Math.abs(point.y - 256) <= 2)) {
            expect(point.x).toBeLessThanOrEqual(start.x + 2);
        }
    });

    it('has no outline for things that aren\'t ship designs', () => {
        expect(getShieldPath('chevron')).toBeNull();
        expect(getShieldPath('circle')).toBeNull();
    });
});

describe('getShieldDotPattern', () => {
    const spacing = 100 / shieldDotCount;

    /** The positions along the outline that the pattern puts a dot at. */
    function litPositions(level: number, dotCount?: number) {
        const pattern = getShieldDotPattern(level, dotCount);
        if (!pattern) {
            return [];
        }

        const lengths = pattern.dasharray.split(' ').map(Number);
        const positions: number[] = [];
        let distance = 0;
        for (let i = 0; i < lengths.length; i += 2) {
            positions.push(((distance - pattern.dashoffset) % 100 + 100) % 100);
            distance += lengths[i] + lengths[i + 1];
        }
        return positions.sort((a, b) => a - b);
    }

    it('lights nothing with no shields', () => {
        expect(getShieldDotPattern(0)).toBeNull();
    });

    it('lights every dot with full shields', () => {
        expect(getShieldDotPattern(100)).toEqual({ dasharray: `0 ${spacing}`, dashoffset: 0 });
    });

    it('always lights at least one dot when shields are up, and leaves one unlit when they aren\'t full', () => {
        expect(litPositions(0.1)).toHaveLength(1);
        expect(litPositions(99.9)).toHaveLength(shieldDotCount - 1);
    });

    it.each([1, 25, 50, 55, 75, 99])('at %i%% lights its share of the dots', (level) => {
        expect(litPositions(level)).toHaveLength(Math.round(level / 100 * shieldDotCount));
    });

    it.each([25, 50, 55, 75])('at %i%% puts the dots on the track\'s positions, around the nose', (level) => {
        const positions = litPositions(level);

        for (const position of positions) {
            const steps = position / spacing;
            expect(steps).toBeCloseTo(Math.round(steps), 6);
        }

        expect(positions[0]).toBeCloseTo(0, 6);
        const forward = positions.filter(position => position < 50).length;
        const back = positions.length - forward;
        expect(Math.abs(forward - back)).toBeLessThanOrEqual(2);
    });

    it('can use a different number of dots', () => {
        const positions = litPositions(50, 120);

        expect(positions).toHaveLength(60);
        expect(positions[1] - positions[0]).toBeCloseTo(100 / 120, 6);
    });
});
